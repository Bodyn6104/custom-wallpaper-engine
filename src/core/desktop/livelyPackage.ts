export function buildLivelyPackage(result: GenerationResult, outDir: string): void {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'shader.frag'), result.shaderCode, 'utf-8');
  fs.writeFileSync(path.join(outDir, 'index.html'), buildIndexHtml(result), 'utf-8');
  fs.writeFileSync(
    path.join(outDir, 'LivelyProperties.json'),
    JSON.stringify(buildLivelyProperties(result.params), null, 2),
    'utf-8'
  );
  fs.writeFileSync(
    path.join(outDir, 'LivelyInfo.json'),
    JSON.stringify(buildLivelyInfo(result), null, 2),
    'utf-8'
  );
  const placeholder = Buffer.from(PLACEHOLDER_JPEG_BASE64, 'base64');
  fs.writeFileSync(path.join(outDir, 'thumbnail.jpg'), placeholder);
  fs.writeFileSync(path.join(outDir, 'preview.jpg'), placeholder);
}

// Schema verified in M0 against a real shipped Lively package
// (rocksdanister/WebGL-Fluid-Simulation, "lively" branch, LivelyInfo.json).
// Type: 1 = web/HTML wallpaper.
export function buildLivelyInfo(result: GenerationResult): Record<string, unknown> {
  return {
    AppVersion: '2.2.1.0',
    Title: result.suggestedTitle,
    Thumbnail: 'thumbnail.jpg',
    Preview: 'preview.jpg',
    Desc: 'Generated by Custom Wallpaper Engine',
    Author: 'CWE',
    License: '',
    Contact: '',
    Type: 1,
    Arguments: '',
    FileName: 'index.html',
  };
}

export function buildLivelyProperties(params: ShaderParam[]): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  for (const param of params) {
    properties[param.name] = {
      type: param.type === 'float' ? 'slider' : param.type === 'color' ? 'color' : 'checkbox',
      value: param.default,
      min: param.min,
      max: param.max,
      text: param.label,
    };
  }
  return properties;
}

/**
 * GLSL has no string literals, so `</script` can only ever appear inside a shader
 * comment — but it still closes the host <script> block and turns whatever follows
 * into live markup. Neutralised here rather than by switching the page to
 * fetch('shader.frag'): Lively serves these pages from disk, and fetch() against a
 * file:// origin is blocked by Chromium's CORS rules.
 */
function escapeForScriptBlock(source: string): string {
  return source.replace(/<\/script/gi, '<\\/script');
}

function buildIndexHtml(result: GenerationResult): string {
  const defaultValues = Object.fromEntries(result.params.map((p) => [p.name, p.default]));

  // JSON.stringify, not '${p.name}' — the name is written into executable JavaScript,
  // and a quote in it would otherwise end the string and run whatever came next.
  const uniformSetters = result.params
    .map((p) => {
      const key = JSON.stringify(p.name);
      if (p.type === 'color')
        return `  if (uniformLocs[${key}]) gl.uniform3fv(uniformLocs[${key}], hexToVec3(values[${key}]));`;
      if (p.type === 'bool')
        return `  if (uniformLocs[${key}]) gl.uniform1i(uniformLocs[${key}], values[${key}] ? 1 : 0);`;
      return `  if (uniformLocs[${key}]) gl.uniform1f(uniformLocs[${key}], values[${key}]);`;
    })
    .join('\n');

  const uniformLookups = result.params
    .map(
      (p) =>
        `  uniformLocs[${JSON.stringify(p.name)}] = gl.getUniformLocation(program, ${JSON.stringify(`u_${p.name}`)});`
    )
    .join('\n');

  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>html,body,canvas{margin:0;padding:0;width:100%;height:100%;display:block;overflow:hidden;background:#000;}</style>
</head>
<body>
<canvas id="c"></canvas>
<script id="frag" type="x-shader/x-fragment">
${escapeForScriptBlock(result.shaderCode)}
</script>
<script>
const canvas = document.getElementById('c');
const gl = canvas.getContext('webgl');
function resize() {
  canvas.width = window.innerWidth * (window.devicePixelRatio || 1);
  canvas.height = window.innerHeight * (window.devicePixelRatio || 1);
  gl.viewport(0, 0, canvas.width, canvas.height);
}
window.addEventListener('resize', resize);
resize();

// Lively's LivelyProperties.json color values are "#RRGGBB" hex strings, not
// [r,g,b] arrays (verified in M0 against real shipped packages) — convert here.
function hexToVec3(hex) {
  const v = (hex || '#000000').replace('#', '');
  return [
    parseInt(v.substring(0, 2), 16) / 255,
    parseInt(v.substring(2, 4), 16) / 255,
    parseInt(v.substring(4, 6), 16) / 255,
  ];
}

const vsSource = 'attribute vec2 position; void main() { gl_Position = vec4(position, 0.0, 1.0); }';
const fsSource = document.getElementById('frag').textContent;

// Without this the only symptom of a bad shader is a black desktop, with the
// actual GLSL diagnostic discarded.
function showError(message) {
  console.error(message);
  const pre = document.createElement('pre');
  pre.textContent = message;
  pre.style.cssText = 'position:fixed;top:0;left:0;right:0;bottom:0;margin:0;padding:16px;overflow:auto;color:#ff6b6b;background:#000;font:12px/1.5 monospace;white-space:pre-wrap;';
  document.body.appendChild(pre);
}

function compile(type, source, label) {
  const shader = gl.createShader(type);
  gl.shaderSource(shader, source);
  gl.compileShader(shader);
  if (!gl.getShaderParameter(shader, gl.COMPILE_STATUS)) {
    showError(label + ' shader failed to compile:\n\n' + gl.getShaderInfoLog(shader));
    gl.deleteShader(shader);
    return null;
  }
  return shader;
}

const values = ${JSON.stringify(defaultValues)};

window.livelyPropertyListener = function(name, value) {
  if (name in values) {
    values[name] = value;
  }
};

const vs = compile(gl.VERTEX_SHADER, vsSource, 'Vertex');
const fs = compile(gl.FRAGMENT_SHADER, fsSource, 'Fragment');
let program = null;
if (vs && fs) {
  program = gl.createProgram();
  gl.attachShader(program, vs);
  gl.attachShader(program, fs);
  gl.linkProgram(program);
  if (!gl.getProgramParameter(program, gl.LINK_STATUS)) {
    showError('Shader program failed to link:\n\n' + gl.getProgramInfoLog(program));
    gl.deleteProgram(program);
    program = null;
  }
}

if (program) {
  gl.useProgram(program);

  const buffer = gl.createBuffer();
  gl.bindBuffer(gl.ARRAY_BUFFER, buffer);
  gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1,-1, 3,-1, -1,3]), gl.STATIC_DRAW);
  const positionLoc = gl.getAttribLocation(program, 'position');
  gl.enableVertexAttribArray(positionLoc);
  gl.vertexAttribPointer(positionLoc, 2, gl.FLOAT, false, 0, 0);

  const iTimeLoc = gl.getUniformLocation(program, 'iTime');
  const iResolutionLoc = gl.getUniformLocation(program, 'iResolution');
  const uniformLocs = {};
${uniformLookups}

  function setUniforms() {
${uniformSetters}
  }

  const start = performance.now();
  function frame(now) {
    gl.uniform1f(iTimeLoc, (now - start) / 1000);
    gl.uniform2f(iResolutionLoc, canvas.width, canvas.height);
    setUniforms();
    gl.drawArrays(gl.TRIANGLES, 0, 3);
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
}
</script>
</body>
</html>`;
}
